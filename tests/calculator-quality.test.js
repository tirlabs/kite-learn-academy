const assert=require('assert');
global.window=global;
require('../js/calculators/calculator-format.js');
const {calculate}=require('../js/calculators/calculator-engine.js');
const near=(actual,expected,tol=0.01)=>assert.ok(Math.abs(actual-expected)<=tol,`${actual} != ${expected}`);
const rd0=calculate('rd',{monthlyDeposit:5000,annualRate:0,years:5});
assert.strictEqual(rd0.primary,300000);
const rd1=calculate('rd',{monthlyDeposit:1000,annualRate:12,years:1});
const rm=Math.pow(1+0.12/4,1/3)-1;let expected=0;for(let i=0;i<12;i++)expected=expected*(1+rm)+1000;
near(rd1.primary,expected,1e-8);
const ppf0=calculate('ppf',{annualDeposit:100000,annualRate:0,years:15});
assert.strictEqual(ppf0.primary,1500000);
const ppf1=calculate('ppf',{annualDeposit:100000,annualRate:12,years:15});
let p=0;for(let y=0;y<15;y++){p+=100000;let interest=0;for(let m=0;m<12;m++)interest+=p*.12/12;p+=interest;}
near(ppf1.primary,p,1e-6);
assert.throws(()=>calculate('ppf',{annualDeposit:100000,annualRate:7.1,years:16}),/5-year extension/);
const brokerage=calculate('brokerage',{buyPrice:100,sellPrice:110,quantity:100,brokeragePerSide:20,otherCharges:10});
assert.strictEqual(brokerage.invested,1000);assert.strictEqual(brokerage.growth,50);assert.strictEqual(brokerage.secondary,950);assert.strictEqual(brokerage.primary,950);
const dividend=calculate('dividend',{shares:100,dividendPerShare:5,marketPrice:250});
assert.strictEqual(dividend.invested,25000);assert.strictEqual(dividend.growth,500);near(dividend.secondary,2);
const avg=calculate('stock-average',{quantity1:10,price1:250,quantity2:10,price2:230});
assert.strictEqual(avg.invested,4800);assert.strictEqual(avg.growth,20);assert.strictEqual(avg.secondary,undefined);
const sizing=calculate('position-sizing',{capital:100000,riskPercent:1,entry:250,stop:240});
assert.strictEqual(sizing.primary,100);assert.strictEqual(sizing.invested,1000);assert.strictEqual(sizing.growth,25000);assert.strictEqual(sizing.secondary,10);
const retirement=calculate('retirement',{currentAge:35,retirementAge:60,monthlyExpense:50000,inflationRate:6,postReturn:7,retirementYears:25});
assert.ok(retirement.invested>0&&retirement.growth===retirement.invested*12);assert.strictEqual(retirement.secondary,'25 years');
const x=calculate('xirr',{cashflows:'2024-01-01,-100000\n2024-12-31,110000'});
near(x.primary,10,0.0001);
console.log('Calculator quality tests passed: timing, PPF conventions, result mappings, retirement and XIRR.');
